import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fixture } from './helpers.mjs';
import { inspectMigration, migrate, restore } from '../src/migrations.mjs';

test('schema-v1 migration dry run preserves bytes and restore is rehearsal-tested', async t => {
  const { engine, dir } = await fixture(t);
  await engine.start();
  const statePath = path.join(dir, '.far/state.json');
  const original = JSON.parse(await fs.readFile(statePath, 'utf8'));
  original.schemaVersion = 1;
  delete original.lifecycle;
  delete original.outcome;
  delete original.pauseReason;
  delete original.escalationRequests;
  delete original.approvalGrants;
  delete original.budget;
  delete original.dispatch;
  delete original.progress;
  delete original.plan;
  original.options = { parallel: 1, modelMode: 'auto' };
  await fs.writeFile(statePath, `${JSON.stringify(original, null, 2)}\n`);
  const before = await fs.readFile(statePath, 'utf8');
  const report = await inspectMigration(dir);
  assert.equal(report.status, 'ready');
  const dry = await migrate(dir, { dryRun: true });
  assert.equal(dry.status, 'dry-run');
  assert.equal(await fs.readFile(statePath, 'utf8'), before);
  const applied = await migrate(dir, { dryRun: false });
  assert.equal(applied.status, 'applied');
  assert.equal(JSON.parse(await fs.readFile(statePath, 'utf8')).schemaVersion, 2);
  const restored = await restore(dir, applied.backup);
  assert.equal(restored.status, 'restored');
  assert.equal(JSON.parse(await fs.readFile(statePath, 'utf8')).schemaVersion, 1);
  const repeated = await migrate(dir, { dryRun: false });
  assert.equal(repeated.status, 'applied');
});
